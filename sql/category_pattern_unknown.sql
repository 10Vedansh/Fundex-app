-- Keyword patterns for Unknown category (named only)
WITH patterns AS (
  SELECT
    CASE
      WHEN UPPER(scheme_name) LIKE '%FMP%' OR UPPER(scheme_name) LIKE '%FIXED MATURITY%' THEN 'FMP / FIXED MATURITY'
      WHEN UPPER(scheme_name) LIKE '%LIQUID%' THEN 'LIQUID'
      WHEN UPPER(scheme_name) LIKE '%OVERNIGHT%' THEN 'OVERNIGHT'
      WHEN UPPER(scheme_name) LIKE '%GILT%' OR UPPER(scheme_name) LIKE '%GOVT%SEC%' OR UPPER(scheme_name) LIKE '%G SEC%' THEN 'GILT / GOVT SECURITIES'
      WHEN UPPER(scheme_name) LIKE '%CORPORATE BOND%' OR UPPER(scheme_name) LIKE '%CORP BOND%' THEN 'CORPORATE BOND'
      WHEN UPPER(scheme_name) LIKE '%CREDIT RISK%' THEN 'CREDIT RISK'
      WHEN UPPER(scheme_name) LIKE '%SHORT DURATION%' OR UPPER(scheme_name) LIKE '%SHORT TERM%' THEN 'SHORT DURATION'
      WHEN UPPER(scheme_name) LIKE '%ULTRA SHORT%' THEN 'ULTRA SHORT DURATION'
      WHEN UPPER(scheme_name) LIKE '%LOW DURATION%' THEN 'LOW DURATION'
      WHEN UPPER(scheme_name) LIKE '%MEDIUM DURATION%' OR UPPER(scheme_name) LIKE '%MEDIUM TERM%' THEN 'MEDIUM DURATION'
      WHEN UPPER(scheme_name) LIKE '%LONG DURATION%' THEN 'LONG DURATION'
      WHEN UPPER(scheme_name) LIKE '%MONEY MARKET%' THEN 'MONEY MARKET'
      WHEN UPPER(scheme_name) LIKE '%DYNAMIC BOND%' THEN 'DYNAMIC BOND'
      WHEN UPPER(scheme_name) LIKE '%BANKING AND PSU%' OR UPPER(scheme_name) LIKE '%BANKING & PSU%' THEN 'BANKING & PSU'
      WHEN UPPER(scheme_name) LIKE '%FLOATER%' OR UPPER(scheme_name) LIKE '%FLOATING RATE%' THEN 'FLOATER'
      WHEN UPPER(scheme_name) LIKE '%INCOME%' THEN 'INCOME'
      WHEN UPPER(scheme_name) LIKE '%ARBITRAGE%' THEN 'ARBITRAGE'
      WHEN UPPER(scheme_name) LIKE '%BALANCED%' THEN 'BALANCED / HYBRID'
      WHEN UPPER(scheme_name) LIKE '%AGGRESSIVE%' THEN 'AGGRESSIVE HYBRID'
      WHEN UPPER(scheme_name) LIKE '%CONSERVATIVE%' THEN 'CONSERVATIVE HYBRID'
      WHEN UPPER(scheme_name) LIKE '%EQUITY SAVINGS%' OR UPPER(scheme_name) LIKE '%EQUITY SAVER%' THEN 'EQUITY SAVINGS'
      WHEN UPPER(scheme_name) LIKE '%DYNAMIC ASSET%' OR UPPER(scheme_name) LIKE '%DYNAMIC ALLOCATION%' THEN 'DYNAMIC ASSET ALLOCATION'
      WHEN UPPER(scheme_name) LIKE '%MULTI ASSET%' THEN 'MULTI ASSET ALLOCATION'
      WHEN UPPER(scheme_name) LIKE '%LARGE CAP%' THEN 'LARGE CAP'
      WHEN UPPER(scheme_name) LIKE '%MID CAP%' THEN 'MID CAP'
      WHEN UPPER(scheme_name) LIKE '%SMALL CAP%' THEN 'SMALL CAP'
      WHEN UPPER(scheme_name) LIKE '%LARGE %MID CAP%' OR UPPER(scheme_name) LIKE '%LARGE AND MID CAP%' THEN 'LARGE & MID CAP'
      WHEN UPPER(scheme_name) LIKE '%MULTI CAP%' OR UPPER(scheme_name) LIKE '%MULTICAP%' THEN 'MULTI CAP'
      WHEN UPPER(scheme_name) LIKE '%FLEXI CAP%' OR UPPER(scheme_name) LIKE '%FLEXICAP%' THEN 'FLEXI CAP'
      WHEN UPPER(scheme_name) LIKE '%VALUE%' AND UPPER(scheme_name) NOT LIKE '%DIVIDEND%' THEN 'VALUE'
      WHEN UPPER(scheme_name) LIKE '%DIVIDEND YIELD%' THEN 'DIVIDEND YIELD'
      WHEN UPPER(scheme_name) LIKE '%FOCUSED%' THEN 'FOCUSED'
      WHEN UPPER(scheme_name) LIKE '%ELSS%' OR UPPER(scheme_name) LIKE '%TAX SAVER%' OR UPPER(scheme_name) LIKE '%TAX PLAN%' THEN 'ELSS'
      WHEN UPPER(scheme_name) LIKE '%ETF%' THEN 'ETF'
      WHEN UPPER(scheme_name) LIKE '%BANKING%' OR UPPER(scheme_name) LIKE '%FINANCIAL%' THEN 'SECTORAL - BANKING/FINANCIAL'
      WHEN UPPER(scheme_name) LIKE '%INFRASTRUCTURE%' OR UPPER(scheme_name) LIKE '%INFRA%' THEN 'SECTORAL - INFRA'
      WHEN UPPER(scheme_name) LIKE '%PHARMA%' OR UPPER(scheme_name) LIKE '%HEALTHCARE%' OR UPPER(scheme_name) LIKE '%HEALTH CARE%' THEN 'SECTORAL - PHARMA/HEALTH'
      WHEN UPPER(scheme_name) LIKE '%TECHNOLOGY%' OR UPPER(scheme_name) LIKE '% IT %' THEN 'SECTORAL - TECHNOLOGY'
      WHEN UPPER(scheme_name) LIKE '%CONSUMPTION%' OR UPPER(scheme_name) LIKE '%CONSUMER%' THEN 'SECTORAL - CONSUMPTION'
      WHEN UPPER(scheme_name) LIKE '%PSU%' THEN 'SECTORAL - PSU'
      WHEN UPPER(scheme_name) LIKE '%MANUFACTURING%' THEN 'SECTORAL - MANUFACTURING'
      WHEN UPPER(scheme_name) LIKE '%ESG%' THEN 'THEMATIC - ESG'
      WHEN UPPER(scheme_name) LIKE '%BUSINESS CYCLE%' THEN 'THEMATIC - BUSINESS CYCLE'
      WHEN UPPER(scheme_name) LIKE '%INTERNATIONAL%' OR UPPER(scheme_name) LIKE '%GLOBAL%' OR UPPER(scheme_name) LIKE '%OVERSEAS%' OR UPPER(scheme_name) LIKE '%FOREIGN%' OR UPPER(scheme_name) LIKE '%EMERGING MARKETS%' OR UPPER(scheme_name) LIKE '%WORLD%' THEN 'INTERNATIONAL'
      WHEN UPPER(scheme_name) LIKE '%GOLD%' OR UPPER(scheme_name) LIKE '%SILVER%' THEN 'COMMODITY - GOLD/SILVER'
      WHEN UPPER(scheme_name) LIKE '%CHILDREN%' OR UPPER(scheme_name) LIKE '%CHILD%' OR UPPER(scheme_name) LIKE '%BAL VIKAS%' THEN 'CHILDREN FUND'
      WHEN UPPER(scheme_name) LIKE '%RETIREMENT%' OR UPPER(scheme_name) LIKE '%PENSION%' THEN 'RETIREMENT'
      WHEN UPPER(scheme_name) LIKE '%CAPITAL PROTECTION%' THEN 'CAPITAL PROTECTION'
      WHEN UPPER(scheme_name) LIKE '%INTERVAL%' THEN 'INTERVAL FUND'
      WHEN UPPER(scheme_name) LIKE '%MIP%' OR UPPER(scheme_name) LIKE '%MONTHLY INCOME%' THEN 'MONTHLY INCOME PLAN'
      WHEN UPPER(scheme_name) LIKE '%FIXED HORIZON%' THEN 'FIXED HORIZON'
      WHEN UPPER(scheme_name) LIKE '%FOF%' OR UPPER(scheme_name) LIKE '%FUND OF FUND%' THEN 'FUND OF FUNDS'
      ELSE 'NO PATTERN MATCHED'
    END AS keyword
  FROM fund_master_enriched
  WHERE category = 'Unknown'
    AND scheme_name IS NOT NULL AND scheme_name != ''
)
SELECT keyword, COUNT(*) AS cnt
FROM patterns
GROUP BY keyword
ORDER BY cnt DESC;
